import json
import re
from pathlib import Path

import vltest_bootstrap

test.scenarios('vlt')

out_filename = test.obj_dir + "/model-manifest.json"

test.compile(verilator_flags2=['--model-manifest-output', out_filename, '--stats'],
             verilator_make_gmake=False,
             make_top_shell=False,
             make_main=False)

with open(out_filename, 'r', encoding='utf8') as fh:
    manifest = json.load(fh)

if manifest['schema_version'] != 1:
    test.error('unexpected model manifest schema')
if manifest['surface'] != 'verilator_model_manifest_experimental':
    test.error('unexpected model manifest surface')
if manifest['model']['top'] != 't':
    test.error('unexpected model top')

coverage = manifest['coverage']
if coverage['status'] != 'not_present':
    test.error('non-covered model reports a coverage mapping')
if any(coverage[name] for name in ('storages', 'lowering_declarations', 'semantic_observations',
                                   'bindings', 'physical_words', 'update_regions')):
    test.error('non-covered model reports coverage records')
if manifest['limitations']['coverage_mapping'] != 'not_present':
    test.error('non-covered model overclaims a coverage mapping')

eval_regions = manifest['eval_regions']
if eval_regions['status'] != 'provided':
    test.error('eval region manifest is not provided')
if manifest['limitations']['eval_regions'] != 'provided':
    test.error('model limitations do not declare eval regions')
if eval_regions['classification_policy']['precedence'] != [
        'host_dependent', 'unknown', 'proven_device_clean'
]:
    test.error('incorrect eval classification precedence')

fields = {field['field_id']: field for field in manifest['fields']}
if manifest['field_count'] != len(fields):
    test.error('incorrect model manifest field count')
for field_id, width, direction in (('rtl:t.clk', 1, 'INPUT'), ('rtl:t.data_i', 8, 'INPUT'),
                                   ('rtl:t.data_o', 8, 'OUTPUT'), ('rtl:t.__Vuser_q', 1, 'NONE'),
                                   ('rtl:t.state_q', 8, 'NONE'), ('rtl:status_if.done', 1,
                                                                  'NONE')):
    field = fields.get(field_id)
    if field is None:
        test.error('missing model manifest field ' + field_id)
    elif field['width_bits'] != width or field['direction'] != direction:
        test.error('incorrect model manifest field ' + field_id)

if not any(field['origin'] == 'compiler_generated' for field in manifest['fields']):
    test.error('missing compiler-generated model field')
if manifest['limitations']['semantic_state_classification'] != 'not_provided':
    test.error('experimental manifest overclaims semantic state classification')
if any('byte_offset' in field['generated_binding'] for field in manifest['fields']):
    test.error('experimental manifest overclaims generated byte offsets')

functions = {function['function_id']: function for function in eval_regions['functions']}
if len(functions) != len(eval_regions['functions']):
    test.error('duplicate eval function identity')
regions = eval_regions['regions']
if len(regions) != 1:
    test.error('main eval region is not unique')
else:
    region = regions[0]
    entry = functions.get(region['entry_function_id'])
    if entry is None or not entry['is_eval_entry']:
        test.error('main eval region does not bind the compiler-owned eval entry')
    elif entry['classification'] != 'unknown':
        test.error('raw generated C++ in main eval does not fail closed')
    if region['schedule_semantics'] != 'not_provided':
        test.error('eval region overclaims schedule semantics')
    if region['convergence_semantics'] != 'not_provided':
        test.error('eval region overclaims convergence semantics')

if not any(function['classification'] == 'proven_device_clean' for function in functions.values()):
    test.error('model manifest has no proven-clean generated function')
for function in functions.values():
    for access in function['direct_state_accesses']:
        if access['field_id'] not in fields:
            test.error('eval state access refers to an unknown field')
    for call in function['direct_calls']:
        if call['callee_function_id'] not in functions:
            test.error('eval call refers to an unknown generated function')

rank = {'proven_device_clean': 0, 'unknown': 1, 'host_dependent': 2}
computed = {
    function_id: rank[function['direct_classification']]
    for function_id, function in functions.items()
}
changed = True
while changed:
    changed = False
    for function_id, function in functions.items():
        propagated = max([computed[function_id]] + [
            computed[call['callee_function_id']] for call in function['direct_calls']
        ])
        if propagated != computed[function_id]:
            computed[function_id] = propagated
            changed = True
for function_id, function in functions.items():
    if rank[function['classification']] != computed[function_id]:
        test.error('eval classification is not the call-closure fixed point')

eval_metrics = eval_regions['metrics']
if eval_metrics['function_count'] != len(functions):
    test.error('incorrect eval function count')
if eval_metrics['region_count'] != len(regions):
    test.error('incorrect eval region count')
metric_sources = {
    'direct_call_edge_count': sum(len(function['direct_calls']) for function in functions.values()),
    'direct_call_site_count': sum(
        call['site_count'] for function in functions.values() for call in function['direct_calls']),
    'state_access_binding_count': sum(
        len(function['direct_state_accesses']) for function in functions.values()),
    'state_read_site_count': sum(
        access['read_site_count'] for function in functions.values()
        for access in function['direct_state_accesses']),
    'state_write_site_count': sum(
        access['write_site_count'] for function in functions.values()
        for access in function['direct_state_accesses']),
    'coverage_update_site_count': sum(
        function['direct_effects']['coverage_update_site_count']
        for function in functions.values()),
    'host_dependency_site_count': sum(
        dependency['site_count'] for function in functions.values()
        for dependency in function['direct_effects']['host_dependencies']),
    'unknown_effect_site_count': sum(
        effect['site_count'] for function in functions.values()
        for effect in function['direct_effects']['unknown_effects']),
    'direct_proven_device_clean_function_count': sum(
        function['direct_classification'] == 'proven_device_clean'
        for function in functions.values()),
    'direct_unknown_function_count': sum(
        function['direct_classification'] == 'unknown' for function in functions.values()),
    'direct_host_dependent_function_count': sum(
        function['direct_classification'] == 'host_dependent'
        for function in functions.values()),
    'proven_device_clean_function_count': sum(
        function['classification'] == 'proven_device_clean' for function in functions.values()),
    'unknown_function_count': sum(
        function['classification'] == 'unknown' for function in functions.values()),
    'host_dependent_function_count': sum(
        function['classification'] == 'host_dependent' for function in functions.values()),
}
for metric, expected in metric_sources.items():
    if eval_metrics[metric] != expected:
        test.error('incorrect eval metric ' + metric)

checkpoint = manifest['checkpoint_projection']
included_fields = [
    field for field in manifest['fields'] if field['checkpoint_membership']['status'] == 'included'
]
excluded_fields = [
    field for field in manifest['fields'] if field['checkpoint_membership']['status'] == 'excluded'
]
if checkpoint['status'] != 'field_membership_only':
    test.error('model manifest overclaims a complete checkpoint projection')
if checkpoint['included_definition_field_count'] != len(included_fields):
    test.error('incorrect included checkpoint field count')
if checkpoint['excluded_definition_field_count'] != len(excluded_fields):
    test.error('incorrect excluded checkpoint field count')
if len(included_fields) + len(excluded_fields) != len(fields):
    test.error('checkpoint membership does not classify every emitted field')
if fields['rtl:t.state_q']['checkpoint_membership'] != {
        'status': 'included',
        'authority': 'verilator_savable_field_selection',
        'reason': 'serialized_field'
}:
    test.error('incorrect checkpoint membership for state_q')
if checkpoint['runtime_state'] != 'not_provided' or checkpoint['packing'] != 'not_provided':
    test.error('model manifest overclaims checkpoint runtime state or packing')

headers = {}
for field in manifest['fields']:
    binding = field['generated_binding']
    container = binding['container']
    if container not in headers:
        header_path = Path(test.obj_dir) / (container + '.h')
        headers[container] = header_path.read_text(encoding='utf8')
    if not re.search(r'\b' + re.escape(binding['member']) + r'\b', headers[container]):
        test.error('generated binding is absent from header for ' + field['field_id'])

instances = {instance['instance_id']: instance for instance in manifest['instances']}
if manifest['instance_count'] != 2 or len(instances) != 2:
    test.error('incorrect model manifest instance count')
top_instance = instances.get('rtl_instance:t')
status_instance = instances.get('rtl_instance:t.status')
if top_instance is None or not top_instance['is_top']:
    test.error('missing top model manifest instance')
if status_instance is None:
    test.error('missing interface model manifest instance')
elif status_instance['parent_instance_id'] != 'rtl_instance:t':
    test.error('incorrect interface parent instance')
else:
    status_field = fields['rtl:status_if.done']
    if (status_instance['module_binding']['container']
            != status_field['generated_binding']['container']):
        test.error('interface instance does not bind its field container')
    syms_header = Path(test.obj_dir) / (status_instance['generated_binding']['container'] + '.h')
    if not re.search(r'\b' + re.escape(status_instance['generated_binding']['member']) + r'\b',
                     syms_header.read_text(encoding='utf8')):
        test.error('generated interface instance binding is absent from symbol header')

if manifest['limitations']['generated_storage_instances'] != 'provided':
    test.error('model manifest does not declare generated storage instances')
if manifest['limitations']['semantic_instance_topology'] != 'not_provided':
    test.error('model manifest overclaims complete semantic instance topology')
if manifest['limitations']['checkpoint_field_membership'] != 'provided':
    test.error('model manifest does not declare checkpoint field membership')
if manifest['limitations']['pointer_free_checkpoint'] != 'not_provided':
    test.error('model manifest overclaims a pointer-free checkpoint')

test.file_grep(test.stats, r'Model manifest, Fields emitted\s+(\d+)', len(fields))
test.file_grep(test.stats, r'Model manifest, Instances emitted\s+(\d+)', 2)
test.file_grep(test.stats, r'Model manifest, Checkpoint fields included\s+(\d+)',
               len(included_fields))
test.file_grep(test.stats, r'Model manifest, Coverage observations emitted\s+(\d+)', 0)
test.file_grep(test.stats, r'Model manifest, Coverage physical words emitted\s+(\d+)', 0)
test.file_grep(test.stats, r'Model manifest, Eval functions emitted\s+(\d+)', len(functions))
test.file_grep(test.stats, r'Model manifest, Eval regions emitted\s+(\d+)', len(regions))

test.passes()
